"""Модуль параметров систем массового обслуживания с нетерпеливыми заявками.

Включает классы параметров для одно- и многолинейных систем массового обслуживания
(СМО) с учетом интенсивности ухода нетерпеливых заявок (ν).

Позволяет моделировать переходные режимы и анализировать пропускную способность
путем задания фиксированных значений ν.

Классы:
    SingleServerParams: Параметры однолинейной СМО с фиксированной интенсивностью ухода.
    MultiServerParams: Параметры многолинейной СМО с фиксированной интенсивностью ухода.
"""

from dataclasses import dataclass

from app.models.base_params import BasicMultiServerParams, BasicSingleServerParams


@dataclass
class SingleServerParams(BasicSingleServerParams):
    """Параметры однолинейной системы массового обслуживания с нетерпеливыми заявками.

    Все параметры обязательны для корректной работы модели переходного режима.

    Атрибуты:
        nu_rate (float): Интенсивность ухода нетерпеливых заявок из очереди (ν ≥ 0).
        Остальные параметры наследуются от BasicSingleServerParams.
    """

    nu_rate: float  # Интенсивность ухода нетерпеливых заявок (ν)


@dataclass
class MultiServerParams(BasicMultiServerParams):
    """Параметры многолинейной системы массового обслуживания с нетерпеливыми заявками.

    Все параметры обязательны для корректной работы модели переходного режима.

    Атрибуты:
        nu_rate (float): Интенсивность ухода нетерпеливых заявок из очереди (ν ≥ 0).
        Остальные параметры наследуются от BasicMultiServerParams.
    """

    nu_rate: float  # Интенсивность ухода нетерпеливых заявок (ν)
