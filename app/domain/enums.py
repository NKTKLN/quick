"""Модуль перечислений для конфигурации вычислительных параметров СМО.

Содержит набор Enum и Flag классов, определяющих:
    - движки вычислений (CalculationEngine).
    - режимы вычислений (CalculationMode).
    - методы вычислений (CalculationMethod).
    - типы СМО (SystemType).

Эти перечисления используются для гибкой настройки и управления процессом моделирования
и анализа производительности различных видов СМО с нетерпеливыми заявками.
"""

from enum import Enum, Flag, auto


class CalculationEngine(Flag):
    """Флаги движков вычислений, используемых в системе.

    Attributes:
        NUMPY: Стандартные вычисления с использованием библиотеки NumPy.
        MPMATH: Высокоточные вычисления с использованием библиотеки mpmath.
        MERGED: Комбинированный режим, объединяющий NumPy и mpmath.
    """

    NUMPY = auto()
    """Вычисления с использованием библиотеки NumPy (стандартная точность)."""

    MPMATH = auto()
    """Вычисления с использованием библиотеки mpmath (повышенная точность)."""

    MERGED = auto()
    """Комбинированный режим вычислений с применением NumPy и mpmath."""


class CalculationMode(Enum):
    """Перечисление режимов вычислений, применяемых в системе массового обслуживания.

    Позволяет задавать, какие характеристики системы следует рассчитывать.

    Атрибуты:
        AIO: Режим «всё в одном» — выполнение всех вычислений одновременно.
        PROBABILITY: Расчёт вероятностей состояний системы.
        THROUGHPUT: Расчёт пропускной способности системы.
        ABSOLUTE_THROUGHPUT: Расчёт абсолютной пропускной способности системы.
        RELATIVE_THROUGHPUT: Расчёт относительной пропускной способности системы.
        AVG_BUFFER_LENGTH: Расчёт среднего числа заявок в буфере.
        AVG_SYSTEM_LENGTH: Расчёт среднего числа заявок в системе.
        REJECTION_PROBABILITY: Расчёт вероятности отказа системы.
        SERVICE_PROBABILITY: Расчёт вероятности обслуживания заявок в переходном режиме.
    """

    AIO = "Всё в одном"
    """Режим выполнения всех основных вычислений системы одновременно."""

    PROBABILITY = "Вероятностный"
    """Режим расчёта вероятностей состояний системы."""

    THROUGHPUT = "Пропускная способность"
    """Режим расчёта пропускной способности системы."""

    ABSOLUTE_THROUGHPUT = "Абсолютная пропускная способность"
    """Режим расчёта абсолютной пропускной способности системы."""

    RELATIVE_THROUGHPUT = "Относительная пропускная способность"
    """Режим расчёта относительной пропускной способности системы."""

    AVG_BUFFER_LENGTH = "Среднее число заявок в буфере"
    """Режим расчёта среднего числа заявок в буфере."""

    AVG_SYSTEM_LENGTH = "Среднее число заявок в системе"
    """Режим расчёта среднего числа заявок в системе."""

    REJECTION_PROBABILITY = "Вероятность отказа системы"
    """Режим расчёта вероятности отказа системы."""

    SERVICE_PROBABILITY = "Вероятность обслуживания в переходном режиме"
    """Режим расчёта вероятности обслуживания заявок в переходном режиме."""


class CalculationMethod(Enum):
    """Enum методов расчёта математических моделей.

    Указывают, какой тип метода использовать для расчётов.

    Attributes:
        ANALYTICAL: Аналитический метод вычислений.
        NUMERICAL: Численный (приближённый) метод вычислений.
    """

    ANALYTICAL = "Аналитический"
    """Аналитический метод расчёта (точный, при наличии формул)."""

    NUMERICAL = "Численный"
    """Численный метод расчёта (приближённый)."""


class SystemType(Enum):
    """Enum типов систем массового обслуживания (СМО), поддерживаемых системой.

    Используется для указания структуры обслуживающей системы.

    Attributes:
        MULTI: Многоканальная (многолинейная) СМО.
        MAP: СМО с MAP-потоками (марковский модулированный пуассоновский процесс).
        MULTI_MAP: СМО с MAP-потоками и несколькими датчиками.
    """

    MULTI = "Многолинейная"
    """Многоканальная система массового обслуживания."""

    MAP = "С MAP-потоками"
    """Система массового обслуживания с MAP-потоками."""

    MULTI_SENSOR_MAP = "С MAP-потоками и несколькими датчиками"
    """Система массового обслуживания с MAP-потоками и несколькими датчиками."""


class SystemMode(Enum):
    """Enum режимов функционирования системы массового обслуживания (СМО).

    Используется для указания, в каком режиме работает модель — стационарном
    или переходном.

    Attributes:
        TRANSIENT: Переходный режим (нестационарный процесс).
        STEADY: Стационарный режим.
    """

    TRANSIENT = "Переходный"
    """Переходный (нестационарный) режим функционирования."""

    STEADY = "Стационарный"
    """Стационарный режим функционирования."""
