"""Модуль параметров оценки устойчивости СМО.

Устойчивость здесь понимается не в классическом смысле существования
стационарного режима (``rho < 1``), а как способность системы удерживать
качество обслуживания в переходном режиме: базовая характеристика ``a(t)``
не должна опускаться ниже критического уровня ``a_кр`` на всём переходном
интервале. Такое определение взято из ВКР (раздел «Показатель запаса
устойчивости») и перенесено на модель QUICK, где роль ``a(t)`` играет
вероятность обслуживания ``P_serv(t)`` либо пропускная способность ``A(t)``.
"""

from dataclasses import dataclass

from quick.domain.enums import StabilityMetric

# Допустимая доля потерь по умолчанию: 5%, откуда критический уровень
# вероятности обслуживания a_кр = 0.95.
DEFAULT_CRITICAL_SERVICE_PROBABILITY = 0.95

# Порог, начиная с которого система считается устойчивой с запасом:
# K_уст = 1.2 означает 20% запаса сверх критического уровня.
DEFAULT_STABLE_THRESHOLD = 1.2

# Ниже единицы средний уровень обслуживания не дотягивает до критического,
# то есть система неустойчива. Между единицей и порогом запаса режим
# пограничный: требование выполняется, но без резерва.
BORDERLINE_THRESHOLD = 1.0

# Доля от установившегося значения, внутри которой характеристика считается
# вышедшей на режим. Используется для оценки длительности переходного
# процесса t_пер.
DEFAULT_SETTLING_TOLERANCE = 0.05


@dataclass
class StabilityParams:
    """Параметры расчёта коэффициента устойчивости.

    Attributes:
        metric (StabilityMetric): Характеристика, по которой оценивается
            устойчивость. ``SERVICE_PROBABILITY`` — безразмерная величина
            ``a(t) = 1 - P_loss(t)``, ``THROUGHPUT`` — пропускная
            способность ``A(t)`` в заявках за единицу времени.
        critical_level (float): Критический уровень ``a_кр``: минимально
            допустимое значение характеристики. Для вероятности
            обслуживания это ``1 - P_доп``, где ``P_доп`` — допустимая доля
            потерь; для пропускной способности — ``A_crit`` в тех же
            единицах, что и сама ``A(t)``.
        settling_tolerance (float): Относительный допуск, по которому
            определяется момент выхода на установившийся режим и,
            следовательно, длительность переходного процесса ``t_пер``.
        stable_threshold (float): Значение ``K_уст``, начиная с которого
            система считается устойчивой с запасом.
    """

    metric: StabilityMetric = StabilityMetric.SERVICE_PROBABILITY
    critical_level: float = DEFAULT_CRITICAL_SERVICE_PROBABILITY
    settling_tolerance: float = DEFAULT_SETTLING_TOLERANCE
    stable_threshold: float = DEFAULT_STABLE_THRESHOLD

    def validate(self) -> None:
        """Проверяет корректность параметров устойчивости.

        Raises:
            ValueError: При некорректных параметрах.
        """
        if self.critical_level <= 0:
            raise ValueError("Критический уровень a_кр должен быть положителен.")

        if (
            self.metric == StabilityMetric.SERVICE_PROBABILITY
            and self.critical_level >= 1
        ):
            raise ValueError(
                "Критический уровень вероятности обслуживания должен быть "
                "меньше единицы."
            )

        if not 0 < self.settling_tolerance < 1:
            raise ValueError(
                "Допуск выхода на установившийся режим должен лежать в "
                "интервале (0, 1)."
            )

        if self.stable_threshold < BORDERLINE_THRESHOLD:
            raise ValueError(
                "Порог устойчивости не может быть меньше "
                f"{BORDERLINE_THRESHOLD}: ниже него запас отсутствует."
            )
