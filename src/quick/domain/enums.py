"""Модуль перечислений для конфигурации вычислительных параметров СМО.

Содержит набор Enum и Flag классов, определяющих:
    - движки вычислений (CalculationEngine).
    - методы вычислений (CalculationMethod).
    - типы СМО (SystemType).
    - характеристики оценки устойчивости (StabilityMetric).

Эти перечисления используются для гибкой настройки и управления процессом моделирования
и анализа производительности различных видов СМО с нетерпеливыми заявками.
"""

from enum import Enum


class CalculationEngine(Enum):
    """Enum движков вычислений, используемых в системе.

    Attributes:
        NUMPY: Стандартные вычисления с использованием библиотеки NumPy.
        MPMATH: Высокоточные вычисления с использованием библиотеки mpmath.
        MERGED: Комбинированный режим, объединяющий NumPy и mpmath.
    """

    NUMPY = "Numpy (быстрое, для небольших систем)"
    """Вычисления с использованием библиотеки NumPy (стандартная точность)."""

    MPMATH = "Mpmath (точное, для больших систем)"
    """Вычисления с использованием библиотеки mpmath (повышенная точность)."""

    MERGED = "Объединенное (для сложных систем с высокой точностью)"
    """Комбинированный режим вычислений с применением NumPy и mpmath."""


class CalculationMethod(Enum):
    """Enum методов расчёта математических моделей.

    Указывают, какой тип метода использовать для расчётов.

    Attributes:
        ANALYTICAL: Аналитический метод вычислений.
        NUMERICAL: Численный (приближённый) метод вычислений.
        IMITATION: Имитационный метод расчёта.
    """

    ANALYTICAL = "Аналитический"
    """Аналитический метод расчёта (точный, при наличии формул)."""

    NUMERICAL = "Численный"
    """Численный метод расчёта (приближённый)."""

    IMITATION = "Имитационный"
    """Имитационный метод расчёта."""


class SystemType(Enum):
    """Enum типов систем массового обслуживания (СМО), поддерживаемых системой.

    Используется для указания структуры обслуживающей системы.

    Attributes:
        MULTI: Многоканальная (многолинейная) СМО.
        MAP: СМО с Марковскими входными потоками и несколькими датчиками.
    """

    MULTI = "Многолинейная"
    """Многоканальная система массового обслуживания."""

    MAP = "С Марковскими входными потоками и несколькими датчиками"
    """Система массового обслуживания с Марковскими входными потоками и несколькими датчиками."""


class SystemMode(Enum):
    """Enum режимов функционирования системы массового обслуживания (СМО).

    Используется для указания, в каком режиме работает модель - стационарном
    или переходном.

    Attributes:
        TRANSIENT: Переходный режим (нестационарный процесс).
        STEADY: Стационарный режим.
    """

    TRANSIENT = "Переходный"
    """Переходный (нестационарный) режим функционирования."""

    STEADY = "Стационарный"
    """Стационарный режим функционирования."""


class StabilityMetric(Enum):
    """Enum характеристик, по которым оценивается устойчивость СМО.

    Устойчивость определяется через удержание одной базовой характеристики
    выше критического уровня на всём переходном интервале. Выбор между
    двумя вариантами — это выбор единиц: вероятность обслуживания
    безразмерна и сравнима между системами, пропускная способность
    измеряется в заявках за единицу времени и сравнима с требованиями
    к каналу.

    Attributes:
        SERVICE_PROBABILITY: Вероятность обслуживания a(t) = 1 - P_loss(t).
        THROUGHPUT: Пропускная способность A(t).
    """

    SERVICE_PROBABILITY = "Вероятность обслуживания a(t) = 1 - P_loss(t)"
    """Безразмерная характеристика качества обслуживания."""

    THROUGHPUT = "Пропускная способность A(t)"
    """Поток фактически обслуженных заявок."""


class StabilityVerdict(Enum):
    """Enum качественных оценок устойчивости системы.

    Attributes:
        STABLE: Система устойчива с запасом.
        BORDERLINE: Требование выполняется, но запас отсутствует.
        UNSTABLE: Критический уровень не выдерживается.
    """

    STABLE = "Устойчивый"
    """Средний уровень характеристики превышает критический с запасом."""

    BORDERLINE = "Пограничный"
    """Средний уровень выше критического, но запас меньше требуемого."""

    UNSTABLE = "Неустойчивый"
    """Характеристика опускается ниже критического уровня."""
