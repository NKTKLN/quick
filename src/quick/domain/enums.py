"""Модуль перечислений для конфигурации вычислительных параметров СМО.

Содержит набор Enum и Flag классов, определяющих:
    - движки вычислений (CalculationEngine).
    - методы вычислений (CalculationMethod).
    - типы СМО (SystemType).

Эти перечисления используются для гибкой настройки и управления процессом моделирования
и анализа производительности различных видов СМО с нетерпеливыми заявками.
"""

from enum import Enum


class CalculationEngine(Enum):
    """Enum движков вычислений, используемых в системе.

    Attributes:
        NUMPY: Стандартные вычисления с использованием библиотеки NumPy.
        MPMATH: Высокоточные вычисления с использованием библиотеки mpmath.
        MERGED: Комбинированный режим, объединяющий NumPy и mpmath.
    """

    NUMPY = "Numpy (быстрое, для небольших систем)"
    """Вычисления с использованием библиотеки NumPy (стандартная точность)."""

class CalculationMethod(Enum):
    """Enum методов расчёта математических моделей.

    Указывают, какой тип метода использовать для расчётов.

    Attributes:
        IMITATION: Имитационный метод расчёта.
    """

    IMITATION = "Имитационный"
    """Имитационный метод расчёта."""


class SystemType(Enum):
    """Enum типов систем массового обслуживания (СМО), поддерживаемых системой.

    Используется для указания структуры обслуживающей системы.

    Attributes:
        MULTI: Многоканальная (многолинейная) СМО.
        MAP: СМО с Марковскими входными потоками и несколькими датчиками.
    """

    MULTI = "Многолинейная"
    """Многоканальная система массового обслуживания."""

    MAP = "С Марковскими входными потоками и несколькими датчиками"
    """Система массового обслуживания с Марковскими входными потоками и несколькими датчиками."""


class SystemMode(Enum):
    """Enum режимов функционирования системы массового обслуживания (СМО).

    Используется для указания, в каком режиме работает модель - стационарном
    или переходном.

    Attributes:
        TRANSIENT: Переходный режим (нестационарный процесс).
    """

    TRANSIENT = "Переходный"
    """Переходный (нестационарный) режим функционирования."""
