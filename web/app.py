"""Программный комплекс для моделирования и анализа медицинских информационно-измерительных систем.

Модуль реализует веб-интерфейс программного комплекса, предназначенного для
моделирования, анализа и прогноза вероятностных и временных характеристик
медицинских информационно-измерительных систем, представляемых в виде систем
массового обслуживания с ограниченной очередью, нетерпеливыми заявками,
пуассоновским и Марковским входным потоком.

Комплекс обеспечивает задание параметров системы, настройку вычислительного
режима, построение матриц коэффициентов, расчет стационарных и переходных
вероятностей состояний, вычисление характеристик производительности,
визуализацию и экспорт результатов моделирования.
"""

import streamlit as st

from quick.db import DuckDBClient
from quick.utils import setup_logger
from quick.utils.progress import Progress, StreamlitProgressStrategy


def render_description() -> None:
    """Отображает описание программного комплекса на главной странице."""
    st.title(
        "🏥 Программный комплекс для моделирования и анализа медицинских "
        "информационно-измерительных систем"
    )
    st.markdown(
        """## 📘 Назначение программы
Программа предназначена для моделирования, анализа и прогноза вероятностных и
временных характеристик медицинских информационно-измерительных систем,
представляемых в виде систем массового обслуживания с ограниченной очередью,
нетерпеливыми заявками, пуассоновским и Марковским входными потоками.

Программа используется для исследования переходных и стационарных режимов
функционирования системы, оценки вероятности потерь и отказов,
пропускной способности, среднего числа заявок в системе и других показателей
производительности.

## ⚙️ Состав программного комплекса
Комплекс включает в себя следующие программы:

1. **Программа задания параметров системы массового обслуживания** — позволяет
   задавать интенсивность поступления заявок, интенсивность обслуживания,
   интенсивность ухода нетерпеливых заявок, максимальное количество заявок
   в системе, количество обслуживающих процессоров, тип СМО, режим вычисления
   и режим функционирования системы. Для переходного режима задаются начальные
   вероятности состояний, переменные состояния, начальное и конечное время
   моделирования, а также количество временных шагов.

2. **Программа настройки вычислительного режима моделирования** — позволяет
   выбирать аналитический или численный метод расчета, вычислительный движок
   NumPy, mpmath или объединенный режим NumPy + mpmath, а также настраивать
   точность вычислений, допустимую погрешность и кэширование результатов.

3. **Программа построения матрицы коэффициентов для многолинейной системы
   массового обслуживания с пуассоновским входным потоком** — по заданным
   параметрам многолинейной СМО с ограниченной очередью и нетерпеливыми
   заявками формирует матрицу коэффициентов системы дифференциальных уравнений
   Колмогорова для последующего расчета вероятностей состояний в стационарном
   и переходном режимах.

4. **Программа построения матрицы коэффициентов для системы массового
   обслуживания с Марковским входным потоком** — по заданным матрицам
   интенсивностей поступления и обслуживания, а также параметрам интенсивности
   обслуживания и ухода формирует матрицу коэффициентов для СМО,
   описывающей поступление информации от нескольких датчиков разного типа.

5. **Программа расчета стационарных и переходных вероятностей состояний
   системы** — рассчитывает стационарные вероятности состояний для
   многолинейной СМО, а также переходные вероятности состояний для
   поддерживаемых типов систем с использованием аналитических методов и
   численного интегрирования методом Рунге—Кутты 4-го порядка.

6. **Программа расчета характеристик производительности системы массового
   обслуживания** — определяет пропускную способность системы, абсолютную и
   относительную пропускную способность, среднее число заявок в системе,
   вероятность отказа, вероятность потери пакетов, вероятность обслуживания
   заявки и вероятность ухода заявки из системы.

7. **Программа визуализации и экспорта результатов моделирования** — строит
   графики изменения вероятностей состояний системы во времени, графики
   пропускной способности, среднего числа заявок в системе, вероятности
   отказа, вероятности потерь, вероятности обслуживания и других
   характеристик, а также обеспечивает экспорт результатов в формате JSON.

## 🧠 Функции программы
Функциями программы являются:
- расчет вероятностей состояний системы;
- построение матриц коэффициентов для различных типов СМО;
- аналитическое и численное решение систем уравнений Колмогорова;
- расчет характеристик производительности;
- визуализация результатов моделирования;
- экспорт результатов вычислений.

## 💻 Технические требования
- **Тип ЭВМ:** Intel Core i3 / AMD Ryzen 3 или выше;
- **ОЗУ:** не менее 4 ГБ;
- **Свободное дисковое пространство:** не менее 1 ГБ;
- **Язык программирования:** Python 3.12;
- **ОС:** Windows 10/11, Linux;
- **Объем программы:** 525,1 Кбайт.
        """
    )


def main() -> None:
    """Точка входа в приложение Streamlit."""
    setup_logger()

    _ = DuckDBClient()

    Progress.set_strategy(StreamlitProgressStrategy())

    st.set_page_config(
        page_title="Моделирование и анализ медицинских систем",
        layout="wide",
        page_icon="🏥",
    )

    render_description()


if __name__ == "__main__":
    main()
