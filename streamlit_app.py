"""Анализатор медицинских систем массового обслуживания (СМО).

Этот модуль реализует веб-интерфейс для анализа и прогнозирования работы медицинских
информационно-измерительных систем с использованием моделей СМО с нетерпеливыми
заявками.
"""

import streamlit as st

from app.logger import setup_logger

setup_logger()

st.set_page_config(
    page_title="Анализатор медицинских СМО", layout="wide", page_icon="🏥"
)

st.title("🏥 Анализатор медицинских СМО (Систем Массового Обслуживания).")
st.markdown("""
## 🔍 О проекте
Этот инструмент позволяет анализировать и прогнозировать производительность медицинских\
    информационно-измерительных систем с помощью:
- **Однолинейных моделей СМО** (с нетерпеливыми заявками и конечной очередью)
- **Многолинейных моделей СМО** (с параллельной обработкой данных)

Разработано на основе научных исследований Российского технологического университета и\
Института проблем управления РАН.

## 🧠 Описание

Модель используется для анализа работы реального времени медицинских информационно-\
    измерительных систем (например, в реанимациях, операционных и т.п.) с учётом:

- ограниченного размера буфера,
- пуассоновского входного потока,
- отказов и сбоев оборудования,
- ухода нетерпеливых заявок.

Решение модели базируется на системе дифференциальных уравнений Колмогорова и методе\
    матрицы преобразования вероятностей.

## 📌 Ключевые возможности
- **Расчет вероятности потерь данных**
- **Оценка пропускной способности системы**
- **Анализ времени переходных процессов**
- **Оптимизация параметров системы**
- **Визуализация результатов в реальном времени**
""")
