"""Веб-интерфейс анализа медицинских систем массового обслуживания (СМО).

Модуль реализует пользовательский интерфейс для анализа и прогноза производительности
медицинских информационно-измерительных систем. Используются математические модели
СМО с нетерпеливыми заявками и ограниченной длиной очереди.

Основано на исследованиях РТУ МИРЭА и ИПУ РАН.
"""

import streamlit as st

from app.db import DuckDBClient
from app.utils import setup_logger
from app.utils.progress import Progress, StreamlitProgressStrategy


def render_description() -> None:
    """Отображает описание проекта и функциональности на главной странице."""
    st.title("🏥 Анализатор медицинских СМО (Систем Массового Обслуживания)")
    st.markdown(
        """## 🔍 О проекте
Инструмент предназначен для анализа и прогноза производительности медицинских\
информационно-измерительных систем на базе:

- **Однолинейных моделей СМО** (с нетерпеливыми заявками и конечной очередью)
- **Многолинейных моделей СМО** (с параллельной обработкой данных)

Решение базируется на работах Российского технологического университета (РТУ МИРЭА)\
и Института проблем управления РАН.

## 🧠 Описание

Модель учитывает:

- ограниченный размер буфера,
- пуассоновский поток входящих заявок,
- отказы и сбои оборудования,
- поведение нетерпеливых заявок (импульсивный выход).

Метод решения использует систему уравнений Колмогорова и технику\
матричной трансформации вероятностей (probability transition matrix).

## 📌 Ключевые возможности
- **Оценка вероятности потерь данных**
- **Расчет пропускной способности**
- **Анализ переходных режимов**
- **Оптимизация параметров модели**
- **Интерактивная визуализация результатов**
        """
    )


def main() -> None:
    """Точка входа в приложение Streamlit."""
    setup_logger()

    _ = DuckDBClient()

    Progress.set_strategy(StreamlitProgressStrategy())

    st.set_page_config(
        page_title="Анализатор медицинских СМО", layout="wide", page_icon="🏥"
    )

    render_description()


if __name__ == "__main__":
    main()
